import { chromium } from 'playwright';
import { readFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
const [file, out] = process.argv.slice(2); mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const errors = [];
const page = await browser.newPage({ viewport: { width: 412, height: 915 }, deviceScaleFactor: 2, hasTouch: true });
page.on('pageerror', e => errors.push(String(e)));
await page.addInitScript(s => { localStorage.setItem('railhaven2', s); }, readFileSync(file, 'utf8'));
await page.goto('file://' + resolve('dist/index.html')); await page.waitForTimeout(1500);
await page.evaluate(() => { const g = window.railhaven.game; if (g.s.ms) g.s.ms.actNew = false; g.s.money = 60000; });
const shot = async (tag, fn) => { await page.evaluate(fn); await page.waitForTimeout(900); await page.screenshot({ path: `${out}/${tag}.png` }); };
await shot('fleet', () => window.railhaven.openCard({ kind: 'fleet', id: 0 }));
await shot('shed-home', () => window.railhaven.openCard({ kind: 'shed', id: 0 }));
const other = await page.evaluate(() => [...document.querySelectorAll('[data-kind="shed"][data-page]')].map(b => b.dataset.page).find(p => p !== String(window.railhaven.game.world.home)));
await page.evaluate(o => document.querySelector(`[data-kind="shed"][data-page="${o}"]`)?.click(), other);
await page.waitForTimeout(900); await page.screenshot({ path: `${out}/shed-other.png` });
await page.evaluate(() => document.querySelector('[data-act="fleet"][data-k="wag"]')?.click());
await page.waitForTimeout(900); await page.screenshot({ path: `${out}/shed-other-bought.png` });
console.log(errors.join('\n') || 'no page errors', 'other', other);
await browser.close();
