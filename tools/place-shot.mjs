// The build outline on a fresh map, and Rails mode guidance. Usage: node tools/place-shot.mjs [kind]
import { chromium } from 'playwright';
import { existsSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
mkdirSync('shots', { recursive: true });
const kind = process.argv[2] ?? 'wood';
const browser = await chromium.launch({ executablePath: existsSync('/opt/pw-browsers/chromium') ? '/opt/pw-browsers/chromium' : undefined });
const page = await browser.newPage({ viewport: { width: 412, height: 860 }, deviceScaleFactor: 2, hasTouch: true });
const errors = []; page.on('pageerror', e => errors.push(String(e)));
await page.goto('file://' + resolve('dist/index.html') + '?new&seed=4242');
await page.waitForTimeout(1500);
await page.evaluate(() => { window.railhaven.game.s.tut = undefined; window.railhaven.openCard(null); });
await page.click('#buildBtn'); await page.waitForTimeout(300);
await page.click(`#buildMenu button[data-k="${kind}"]`); await page.waitForTimeout(1200);
await page.screenshot({ path: `shots/place-${kind}.png` });
await page.click('#cancel').catch(() => {}); await page.waitForTimeout(200);
await page.click('#bar [data-mode="rail"]'); await page.waitForTimeout(1000);
await page.screenshot({ path: 'shots/rails-start.png' });
console.log(errors.join('\n') || 'no page errors');
await browser.close();
